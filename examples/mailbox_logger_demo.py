async def demo_basic_mailbox_logging():
    """Demonstrate basic mailbox logging functionality"""
    print("\n" + "=" * 60)
    print("DEMO: Basic Mailbox Logging")
    print("=" * 60)

    # Create mailbox logger
    mailbox_logger = MailboxLogger(
        redis_url="redis://localhost:6379",
        log_directory="demo_mailbox_logs",
        channel="beast_mode_network",
        max_log_size_mb=1,  # Small size for demo
        max_log_files=5,
    )

    try:
        print("Starting mailbox logger...")
        await mailbox_logger.start_logging()

        print("✓ Mailbox logger started successfully")
        print(f"✓ Logging to directory: {mailbox_logger.log_directory}")
        print(f"✓ Current log file: {mailbox_logger.current_log_file}")

        # Let it run for a bit to capture any existing messages
        print("\nListening for messages for 3 seconds...")
        await asyncio.sleep(3.0)

        # Check stats
        stats = mailbox_logger.get_logger_stats()
        print(f"\nLogger Statistics:")
        print(f"  Messages logged: {stats['messages_logged']}")
        print(f"  Parsing errors: {stats['parsing_errors']}")
        print(f"  Connection errors: {stats['connection_errors']}")
        print(f"  Runtime: {stats.get('runtime_seconds', 0):.1f} seconds")

        # Get log file information
        log_files = mailbox_logger.get_log_files()
        print(f"\nLog Files ({len(log_files)} total):")
        for log_file in log_files:
            status = " (CURRENT)" if log_file["is_current"] else ""
            print(f"  {Path(log_file['path']).name}: {log_file['size_mb']} MB{status}")

    except Exception as e:
        print(f"✗ Error in mailbox logging: {e}")

    finally:
        print("\nStopping mailbox logger...")
        await mailbox_logger.stop_logging()
        print("✓ Mailbox logger stopped")


async def demo_message_generation_and_logging():
    """Demonstrate logging messages generated by bus clients"""
    print("\n" + "=" * 60)
    print("DEMO: Message Generation and Logging")
    print("=" * 60)

    # Create mailbox logger
    mailbox_logger = MailboxLogger(
        redis_url="redis://localhost:6379",
        log_directory="demo_mailbox_logs",
        channel="beast_mode_network",
    )

    # Create bus clients
    agent1 = BeastModeBusClient(
        redis_url="redis://localhost:6379",
        agent_id="demo_agent_1",
        capabilities=["python", "testing", "demo"],
    )

    agent2 = BeastModeBusClient(
        redis_url="redis://localhost:6379",
        agent_id="demo_agent_2",
        capabilities=["gcp", "terraform", "demo"],
    )

    try:
        # Start mailbox logger
        print("Starting mailbox logger...")
        await mailbox_logger.start_logging()

        # Connect agents
        print("Connecting agents...")
        await agent1.connect()
        await agent2.connect()

        print("✓ All components connected")

        # Generate various types of messages
        print("\nGenerating test messages...")

        # Agent discovery
        await agent1.announce_presence()
        await agent2.announce_presence()
        print("✓ Sent agent discovery messages")

        # Simple messages
        await agent1.send_simple_message("Hello from agent 1!", target="demo_agent_2")
        await agent2.send_simple_message(
            "Hello back from agent 2!", target="demo_agent_1"
        )
        print("✓ Sent simple messages")

        # Help request
        help_request_id = await agent1.send_help_request(
            required_capabilities=["gcp"], description="Need help with GCP deployment"
        )
        print(f"✓ Sent help request: {help_request_id}")

        # Technical exchange
        tech_message = BeastModeMessage(
            type=MessageType.TECHNICAL_EXCHANGE,
            source="demo_agent_1",
            payload={
                "topic": "deployment_config",
                "details": {
                    "environment": "production",
                    "region": "us-central1",
                    "instance_type": "e2-standard-4",
                },
            },
        )
        await agent1.send_message(tech_message)
        print("✓ Sent technical exchange message")

        # Wait for messages to be processed
        print("\nWaiting for messages to be logged...")
        await asyncio.sleep(2.0)

        # Check logger stats
        stats = mailbox_logger.get_logger_stats()
        print(f"\nLogging Results:")
        print(f"  Messages logged: {stats['messages_logged']}")
        print(f"  Parsing errors: {stats['parsing_errors']}")
        print(f"  Last message: {stats['last_message_time']}")

        if stats["messages_logged"] > 0:
            print("✓ Messages successfully logged!")
        else:
            print("⚠ No messages were logged")

    except Exception as e:
        print(f"✗ Error in message generation demo: {e}")

    finally:
        print("\nCleaning up...")
        await agent1.disconnect()
        await agent2.disconnect()
        await mailbox_logger.stop_logging()
        print("✓ All components stopped")


async def demo_mail_checking():
    """Demonstrate checking mail from logged messages"""
    print("\n" + "=" * 60)
    print("DEMO: Mail Checking")
    print("=" * 60)

    # Create mailbox logger (not running, just for reading)
    mailbox_logger = MailboxLogger(log_directory="demo_mailbox_logs")

    try:
        print("Checking mail from logged messages...")

        # Check all messages
        all_messages = await mailbox_logger.check_mail()
        print(f"\nTotal messages in mailbox: {len(all_messages)}")

        if all_messages:
            # Show recent messages
            print("\nRecent messages (last 5):")
            for i, msg_info in enumerate(all_messages[:5]):
                msg = msg_info["message"]
                timestamp = msg_info["log_timestamp"]
                print(f"  {i+1}. [{timestamp}] {msg['type']} from {msg['source']}")
                if msg["type"] == MessageType.SIMPLE_MESSAGE:
                    content = msg["payload"].get("content", "")[:50]
                    print(f"      Content: {content}...")

            # Filter by message type
            simple_messages = await mailbox_logger.check_mail(
                message_types=[MessageType.SIMPLE_MESSAGE]
            )
            print(f"\nSimple messages: {len(simple_messages)}")

            # Filter by source agent
            agent1_messages = await mailbox_logger.check_mail(
                source_agents=["demo_agent_1"]
            )
            print(f"Messages from demo_agent_1: {len(agent1_messages)}")

            # Filter by time (last hour)
            recent_time = datetime.now() - timedelta(hours=1)
            recent_messages = await mailbox_logger.check_mail(since=recent_time)
            print(f"Messages in last hour: {len(recent_messages)}")

            # Limited results
            limited_messages = await mailbox_logger.check_mail(limit=3)
            print(f"Limited to 3 messages: {len(limited_messages)}")

        else:
            print("No messages found in mailbox")
            print("Run the message generation demo first to create some messages")

    except Exception as e:
        print(f"✗ Error checking mail: {e}")


