async def demo_log_rotation():
    """Demonstrate log rotation functionality"""
    print("\n" + "=" * 60)
    print("DEMO: Log Rotation")
    print("=" * 60)

    # Create logger with very small log size for quick rotation
    mailbox_logger = MailboxLogger(
        redis_url="redis://localhost:6379",
        log_directory="demo_mailbox_logs",
        channel="beast_mode_network",
        max_log_size_mb=0.001,  # 1KB for quick rotation
        max_log_files=3,
        rotation_check_interval=1,  # Check every second
    )

    try:
        print("Starting logger with small log size for rotation demo...")
        await mailbox_logger.start_logging()

        # Create a bus client to generate messages
        agent = BeastModeBusClient(
            redis_url="redis://localhost:6379",
            agent_id="rotation_demo_agent",
            capabilities=["demo", "rotation"],
        )

        await agent.connect()

        print("Generating messages to trigger log rotation...")

        # Send many messages to trigger rotation
        for i in range(20):
            await agent.send_simple_message(
                f"Rotation test message {i} with extra content to make it larger "
                + "and trigger log rotation when the file size limit is reached. "
                + f"Message number {i} of 20 total messages for rotation testing."
            )

            if i % 5 == 0:
                print(f"  Sent {i+1} messages...")

            await asyncio.sleep(0.1)

        # Wait for rotation to be processed
        print("Waiting for log rotation to complete...")
        await asyncio.sleep(3.0)

        # Check rotation results
        stats = mailbox_logger.get_logger_stats()
        log_files = mailbox_logger.get_log_files()

        print(f"\nRotation Results:")
        print(f"  Messages logged: {stats['messages_logged']}")
        print(f"  Log rotations: {stats['log_rotations']}")
        print(f"  Total log files: {len(log_files)}")

        print(f"\nLog Files:")
        for log_file in log_files:
            status = " (CURRENT)" if log_file["is_current"] else ""
            print(f"  {Path(log_file['path']).name}: {log_file['size_mb']} MB{status}")

        if stats["log_rotations"] > 0:
            print("✓ Log rotation occurred successfully!")
        else:
            print("⚠ No log rotation occurred (file size may not have exceeded limit)")

    except Exception as e:
        print(f"✗ Error in rotation demo: {e}")

    finally:
        await agent.disconnect()
        await mailbox_logger.stop_logging()


